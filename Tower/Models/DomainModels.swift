        self.alpn = alpn
        self.realityPublicKey = realityPublicKey
        self.realityShortID = realityShortID
        self.certificateFingerprint = certificateFingerprint
        self.fingerprint = fingerprint
        self.flow = flow
        self.skipCertificateVerification = skipCertificateVerification
        self.alterID = alterID
        self.protocolName = protocolName
        self.protocolParam = protocolParam
        self.obfs = obfs
        self.obfsParam = obfsParam
        self.idleSessionCheckInterval = idleSessionCheckInterval
        self.idleSessionTimeout = idleSessionTimeout
        self.minIdleSession = minIdleSession
        self.version = version
        self.congestionControl = congestionControl
        self.udpRelayMode = udpRelayMode
        self.portHopping = portHopping
        self.upMbps = upMbps
        self.downMbps = downMbps
        self.wireGuardPrivateKey = wireGuardPrivateKey
        self.wireGuardPublicKey = wireGuardPublicKey
        self.wireGuardPreSharedKey = wireGuardPreSharedKey
        self.wireGuardIPv4 = wireGuardIPv4
        self.wireGuardIPv6 = wireGuardIPv6
        self.wireGuardAllowedIPs = wireGuardAllowedIPs
        self.wireGuardReserved = wireGuardReserved
        self.wireGuardMTU = wireGuardMTU
        self.wireGuardPersistentKeepalive = wireGuardPersistentKeepalive
        self.wireGuardDNS = wireGuardDNS
        self.rawURI = rawURI
        self.isSubscriptionMetadata = isSubscriptionMetadata
    }

    var endpoint: String {
        let host = server.contains(":") && !(server.hasPrefix("[") && server.hasSuffix("]"))
            ? "[\(server)]"
            : server
        return "\(host):\(port)"
    }
    var canonicalKey: String {
        // Shared front doors are common: an airport may publish many named
        // routes through the same host, port and credential. Those are still
        // distinct nodes when their display name, SNI, transport or other
        // connection parameters differ. Use the complete parsed identity so
        // only an exact repeated node is collapsed.
        var fields = [kind.rawValue, name, server.lowercased(), String(port)]
        fields.append(contentsOf: [cipher ?? "", password ?? "", uuid ?? "", username ?? ""])
        fields.append(contentsOf: [
            transport ?? "", transportMode ?? "", plugin ?? "", tls ? "1" : "0",
            sni ?? "", hostHeader ?? "", path ?? "", alpn ?? ""
        ])
        fields.append(contentsOf: [
            realityPublicKey ?? "", realityShortID ?? "", fingerprint ?? "", flow ?? "",
            skipCertificateVerification ? "1" : "0"
        ])
        fields.append(contentsOf: [
            alterID.map(String.init) ?? "", protocolName ?? "", protocolParam ?? "",
            obfs ?? "", obfsParam ?? ""
        ])
        let idleCheck = idleSessionCheckInterval.map { String($0) } ?? ""
        let idleTimeout = idleSessionTimeout.map { String($0) } ?? ""
        let minimumIdle = minIdleSession.map { String($0) } ?? ""
        let protocolVersion = version.map { String($0) } ?? ""
        fields.append(contentsOf: [certificateFingerprint ?? "", idleCheck, idleTimeout, minimumIdle, protocolVersion])
        fields.append(contentsOf: [
            congestionControl ?? "", udpRelayMode ?? "", portHopping ?? "",
            upMbps.map(String.init) ?? "", downMbps.map(String.init) ?? ""
        ])
        fields.append(contentsOf: [
            wireGuardPrivateKey ?? "", wireGuardPublicKey ?? "", wireGuardPreSharedKey ?? "",
            wireGuardIPv4 ?? "", wireGuardIPv6 ?? "", wireGuardAllowedIPs ?? "",
            wireGuardReserved ?? "", wireGuardMTU.map(String.init) ?? "",
            wireGuardPersistentKeepalive.map(String.init) ?? "", wireGuardDNS ?? ""
        ])
        return fields.joined(separator: "\u{1F}")
    }

    /// Whether this node negotiates REALITY rather than ordinary TLS.
    var usesReality: Bool {
        !(realityPublicKey ?? "").isEmpty
    }

    /// The VMess/VLESS id in the form every client accepts.
    ///
    /// Xray lets the id be any string shorter than 32 bytes and derives a v5
    /// UUID from it — SHA-1 over the nil namespace followed by the text — so
    /// airports do publish ids like `abcd1234`. Clash and Stash refuse anything
    /// that is not a UUID (`invalid UUID length: 8`) and will not load the file
    /// at all, so the same derivation is done here. The server compares against
    /// exactly this value, so the node still connects.
    var exportableUUID: String? {
        guard let uuid else { return nil }
        return ProxyNode.normalizedProxyID(uuid)
    }

    /// The transport path in the form a client will accept.
    ///
    /// WebSocket and HTTP/2 paths are HTTP request paths, so they have to be
    /// absolute, but airports do publish them without the leading slash. Xray's
    /// own server prepends one before matching (`GetNormalizedPath`), so doing
    /// the same here is what the node was always going to send on the wire.
    /// Clash and Shadowrocket quietly normalise it; Surge rejects the whole
    /// profile with "字段 `ws-path` 的值无效".
    var exportablePath: String? {
        guard let path, !path.isEmpty else { return nil }
        return path.hasPrefix("/") ? path : "/" + path
    }

    static func normalizedProxyID(_ value: String) -> String? {
        let trimmed = value.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return nil }
        if UUID(uuidString: trimmed) != nil { return trimmed }
        // Xray's own bound: 32 bytes or more is treated as a malformed UUID
        // rather than a name, and there is nothing faithful to emit for it.
        guard trimmed.utf8.count < 32 else { return nil }
        return derivedUUID(from: trimmed)
    }

    private static func derivedUUID(from text: String) -> String {
        var hasher = Insecure.SHA1()
        hasher.update(data: Data(repeating: 0, count: 16))
        hasher.update(data: Data(text.utf8))
        var bytes = Array(hasher.finalize().prefix(16))
        bytes[6] = (bytes[6] & 0x0F) | (5 << 4)
        bytes[8] = (bytes[8] & 0x3F) | 0x80
        return UUID(uuid: (
            bytes[0], bytes[1], bytes[2], bytes[3], bytes[4], bytes[5], bytes[6], bytes[7],
            bytes[8], bytes[9], bytes[10], bytes[11], bytes[12], bytes[13], bytes[14], bytes[15]
        )).uuidString.lowercased()
    }
    var isLocal: Bool { sourceID == nil }

    var protocolSummary: String {
        var parts: [String] = [protocolDisplayName]

        if let transportDisplayName, !parts.contains(transportDisplayName) {
            parts.append(transportDisplayName)
        }

        if tls, ![.trojan, .hysteria, .hysteria2, .tuic, .wireguard, .anytls, .http].contains(kind), !parts.contains("TLS") {
            parts.append("TLS")
        }

        if supportsUDP {
            parts.append("UDP")
        }
        return parts.joined(separator: " / ")
    }

    private var protocolDisplayName: String {
        switch kind {
        case .shadowsocks: "SHADOWSOCKS"
        case .shadowsocksR: "SHADOWSOCKS R"
        case .vmess: "VMESS"
        case .vless: "VLESS"
        case .trojan: "TROJAN"
        case .hysteria: "HYSTERIA"
        case .hysteria2: "HYSTERIA 2"
        case .tuic: "TUIC"
        case .wireguard: "WIREGUARD"
        case .anytls: "ANYTLS"
        case .snell: version.map { "SNELL V\($0)" } ?? "SNELL"
        case .socks5: "SOCKS5"
        case .http: tls ? "HTTPS" : "HTTP"
        case .unknown: "未知协议"
        }
    }

    private var transportDisplayName: String? {
        let rawTransport: String?
        if let transport, !transport.isEmpty {
            rawTransport = transport
        } else if [.shadowsocks, .shadowsocksR].contains(kind),
                  let obfs, !obfs.isEmpty, obfs.lowercased() != "plain" {
            rawTransport = obfs
        } else {
            rawTransport = nil
        }

        guard let normalized = rawTransport?
            .trimmingCharacters(in: .whitespacesAndNewlines)
            .lowercased(),
            !["", "tcp", "none", "plain"].contains(normalized) else {
            return nil
        }

        return switch normalized {
        case "ws", "websocket": "WS"
        case "grpc": "GRPC"
        case "http", "http_simple": "HTTP"
        case "h2", "http2": "H2"
        case "httpupgrade": "HTTP UPGRADE"
        case "xhttp", "splithttp": "XHTTP"
        case "kcp", "mkcp": "KCP"
        case "quic": "QUIC"
        case "tls1.2_ticket_auth", "tls": "TLS"
        default: normalized.uppercased()
        }
    }

    private var supportsUDP: Bool {
        switch kind {
        case .http, .unknown: false
        // Snell only carries UDP from version 3 onwards.
        case .snell: (version ?? 4) >= 3
        default: true
        }
    }
}

