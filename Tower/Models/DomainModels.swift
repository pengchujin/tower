/// Keeps the subscription name typed by the user stable while the edit sheet
/// dismisses its focused text field. SwiftUI can publish one final empty value
/// during toolbar dismissal, which must not overwrite the last real input.
struct SubscriptionNameDraft: Equatable {
    var text: String {
        didSet {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            if !trimmed.isEmpty {
                lastValidText = text
            }
        }
    }
    private var lastValidText: String?

    init(text: String = "") {
        self.text = text
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        self.lastValidText = trimmed.isEmpty ? nil : text
    }

    var committedName: String {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        return (trimmed.isEmpty ? lastValidText : text)?
            .trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
    }
}

/// Keeps raw in-progress text separate from the persisted export name. An
/// empty draft is valid while editing; the default is restored only on commit.
struct ConfigurationNameDraft: Equatable {
    var text: String {
        didSet {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            if !trimmed.isEmpty {
                lastValidText = text
            }
        }
    }
    private var hasLoadedPersistedName = false
    /// SwiftUI can publish one transient empty string when a focused text
    /// field is dismissed from a parent toolbar. Keep the last value the user
    /// actually entered so that teardown event cannot reset a valid name.
    private var lastValidText: String?

    init(text: String = "") {
        self.text = text
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        self.lastValidText = trimmed.isEmpty ? nil : text
    }

    mutating func loadPersistedNameIfNeeded(_ name: String) {
        guard !hasLoadedPersistedName else { return }
        text = name
        hasLoadedPersistedName = true
    }

    var committedName: String {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        return ExportFilePresentation.profileName(trimmed.isEmpty ? lastValidText : text)
    }
}

enum ExportFilePresentation {
    static func profileName(_ candidate: String?) -> String {
        let trimmed = candidate?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
        let fallback = trimmed.isEmpty ? TowerBrand.localizedName : trimmed
        let forbidden = CharacterSet(charactersIn: "/:\\?%*|\"<>\0")
        let cleaned = fallback.components(separatedBy: forbidden).joined(separator: " ")
            .replacingOccurrences(of: "  ", with: " ")
            .trimmingCharacters(in: .whitespacesAndNewlines)
        return String((cleaned.isEmpty ? TowerBrand.localizedName : cleaned).prefix(80))
    }

    static func contentDisposition(fileName: String) -> String {
        let allowed = CharacterSet.alphanumerics.union(CharacterSet(charactersIn: "-._~"))
        let encoded = fileName.addingPercentEncoding(withAllowedCharacters: allowed) ?? fileName
        let fallback: String
        if fileName.canBeConverted(to: .ascii) {
            fallback = fileName
        } else {
            let fileExtension = (fileName as NSString).pathExtension
            fallback = fileExtension.isEmpty ? "Tower" : "Tower.\(fileExtension)"
        }
        return "attachment; filename=\"\(fallback)\"; filename*=UTF-8''\(encoded)"
    }
}

struct GeneratedConfiguration {
    let target: ClientTarget
    let content: String
    let supportedNodeCount: Int
    let skippedNodeCount: Int
    let ruleCount: Int
    let profileName: String
    let contentMode: ExportContentMode
    let fileExtensionOverride: String?

    init(
        target: ClientTarget,
        content: String,
        supportedNodeCount: Int,
        skippedNodeCount: Int,
        ruleCount: Int,
        profileName: String = TowerBrand.localizedName,
        contentMode: ExportContentMode = .fullConfiguration,
        fileExtensionOverride: String? = nil
    ) {
        self.target = target
        self.content = content
        self.supportedNodeCount = supportedNodeCount
        self.skippedNodeCount = skippedNodeCount
        self.ruleCount = ruleCount
        self.profileName = ExportFilePresentation.profileName(profileName)
        self.contentMode = contentMode
        self.fileExtensionOverride = fileExtensionOverride
    }

    var fileExtension: String { fileExtensionOverride ?? target.fileExtension }

    var fileName: String {
        "\(profileName).\(fileExtension)"
    }

    func named(_ value: String) -> GeneratedConfiguration {
        GeneratedConfiguration(
            target: target,
            content: content,
            supportedNodeCount: supportedNodeCount,
            skippedNodeCount: skippedNodeCount,
            ruleCount: ruleCount,
            profileName: value,
            contentMode: contentMode,
            fileExtensionOverride: fileExtensionOverride
        )
    }
}
