struct ProxyNode: Identifiable, Codable, Hashable {
    let id: UUID
    var sourceID: UUID?
    var kind: ProxyKind
    var name: String
    var server: String
    var port: Int
    var cipher: String?
    var password: String?
    var uuid: String?
    var username: String?
    var transport: String?
    /// Transport-specific mode (currently XHTTP). Kept separate from the
    /// transport name so `xhttp;mode=packet-up` survives a round trip.
    var transportMode: String?
    /// SIP003 plugin used by Shadowsocks. simple-obfs continues to use
    /// `obfs`; this field distinguishes v2ray-plugin from ordinary SS obfs.
    var plugin: String?
    var tls: Bool
    var sni: String?
    var hostHeader: String?
    var path: String?
    var alpn: String?
    /// REALITY's server public key (`pbk`) and short id (`sid`), plus the uTLS
    /// fingerprint (`fp`) and the XTLS flow. A VLESS node that carries these is
    /// a REALITY node: writing it without them yields plain TLS to a borrowed
    /// SNI, which looks fine and never connects.
    var realityPublicKey: String?
    var realityShortID: String?
    /// SHA-256 fingerprint of the server certificate. This is deliberately
    /// separate from `fingerprint`, which is the browser-style uTLS ClientHello
    /// name (`chrome`, `safari`, ...). Mihomo and Shadowrocket accept both and
    /// confusing them produces a syntactically valid profile that cannot
    /// complete its TLS handshake.
    var certificateFingerprint: String?
    var fingerprint: String?
    var flow: String?
    var skipCertificateVerification: Bool
    var alterID: Int?
    var protocolName: String?
    var protocolParam: String?
    var obfs: String?
    var obfsParam: String?
    /// AnyTLS session maintenance controls. Values are seconds, matching the
    /// user-facing fields and Mihomo; sing-box serialises them as durations.
    var idleSessionCheckInterval: Int?
    var idleSessionTimeout: Int?
    var minIdleSession: Int?
    /// Snell's protocol version. It decides both what a client accepts and
    /// whether the node can carry UDP.
    var version: Int?
    /// TUIC's QUIC tuning. `congestionControl` is `bbr`/`cubic`/`new_reno`
    /// and `udpRelayMode` is `native`/`quic`; both are per-server choices the
    /// airport makes, so a wrong guess costs UDP or throughput.
    var congestionControl: String?
    var udpRelayMode: String?
    /// Alternate QUIC destination ports used by Hysteria 2 (and, where a
    /// producer supports it, TUIC). Providers call this `ports`, `mport`,
    /// `server-ports`, or `port-hopping`; using only the display `port` makes
    /// most hops unreachable.
    var portHopping: String?
    /// Hysteria 1's bandwidth budget in Mbps. Unlike Hysteria 2 these are not
    /// optional hints: the protocol's congestion control is rate-based, so a
    /// node without them either fails to load or crawls.
    var upMbps: Int?
    var downMbps: Int?
    /// WireGuard's complete single-peer tunnel configuration. These cannot be
    /// mapped onto generic proxy credentials without losing routing semantics,
    /// so they stay explicit all the way from parser to client producer.
    var wireGuardPrivateKey: String?
    var wireGuardPublicKey: String?
    var wireGuardPreSharedKey: String?
    var wireGuardIPv4: String?
    var wireGuardIPv6: String?
    var wireGuardAllowedIPs: String?
    var wireGuardReserved: String?
    var wireGuardMTU: Int?
    var wireGuardPersistentKeepalive: Int?
    var wireGuardDNS: String?
    var rawURI: String
    /// Airports often encode quota, expiry, web site, or support text as fake
    /// proxy entries. Keeping the marker optional preserves old snapshots while
    /// letting Settings decide whether those entries remain visible/exported.
    var isSubscriptionMetadata: Bool?

    init(
