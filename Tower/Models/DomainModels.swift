        sourceID: UUID? = nil,
        kind: ProxyKind,
        name: String,
        server: String,
        port: Int,
        cipher: String? = nil,
        password: String? = nil,
        uuid: String? = nil,
        username: String? = nil,
        transport: String? = nil,
        transportMode: String? = nil,
        plugin: String? = nil,
        tls: Bool = false,
        sni: String? = nil,
        hostHeader: String? = nil,
        path: String? = nil,
        alpn: String? = nil,
        realityPublicKey: String? = nil,
        realityShortID: String? = nil,
        certificateFingerprint: String? = nil,
        fingerprint: String? = nil,
        flow: String? = nil,
        skipCertificateVerification: Bool = false,
        alterID: Int? = nil,
        protocolName: String? = nil,
        protocolParam: String? = nil,
        obfs: String? = nil,
        obfsParam: String? = nil,
        idleSessionCheckInterval: Int? = nil,
        idleSessionTimeout: Int? = nil,
        minIdleSession: Int? = nil,
        version: Int? = nil,
        congestionControl: String? = nil,
        udpRelayMode: String? = nil,
        portHopping: String? = nil,
        upMbps: Int? = nil,
        downMbps: Int? = nil,
        wireGuardPrivateKey: String? = nil,
        wireGuardPublicKey: String? = nil,
        wireGuardPreSharedKey: String? = nil,
        wireGuardIPv4: String? = nil,
        wireGuardIPv6: String? = nil,
        wireGuardAllowedIPs: String? = nil,
        wireGuardReserved: String? = nil,
        wireGuardMTU: Int? = nil,
        wireGuardPersistentKeepalive: Int? = nil,
        wireGuardDNS: String? = nil,
        rawURI: String,
        isSubscriptionMetadata: Bool? = nil
    ) {
